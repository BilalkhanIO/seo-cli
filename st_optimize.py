def build_html(cfg, body):
    main, related = (body.split(MARK, 1) if MARK in body else (body, ""))
    related = (MARK + related) if MARK in body else ""
    img = ""
    if "<img" not in main.lower():
        img, _ = img_block(cfg["image_query"], cfg.get("image_alt"))
    for cls in ("author-eeat", "key-takeaways"):
        main = re.sub(rf'<div class="{cls}".*?</div>', '', main, flags=re.S)
    main = re.sub(r'<h2>Frequently asked questions</h2>.*?(?=<h2|$)', '', main, flags=re.S)
    main = re.sub(r'<script type="application/ld\+json">.*?</script>', '', main, flags=re.S)
    return eeat(cfg) + takeaways(cfg) + img + table(cfg) + main + faq(cfg) + schema(cfg) + related

def main():
    c = creds()
    b = build("blogger", "v3", credentials=c, cache_discovery=False)
    for k in (ONLY or list(PAGES)):
        cfg = PAGES.get(k)
        if not cfg: print(f"! unknown: {k}"); continue
        post = b.posts().get(blogId=BLOG_ID, postId=cfg["id"]).execute()
        html = build_html(cfg, post["content"])
        errs, warns, words, ni, ne = gate(cfg, html)
        print(f"\n=== {k} === '{cfg['title']}' ({len(cfg['title'])}c) | {words}w | int {ni} ext {ne}")
        print(f"  errors: {errs or 'NONE ✅'} | warns: {warns or 'none'}")
        if APPLY and not errs:
            b.posts().patch(blogId=BLOG_ID, postId=cfg["id"], body={"title": cfg["title"], "content": html}).execute()
            print("  PATCHED. Google discovery uses sitemap/internal links; inspect stored status after recrawl.")
    if not APPLY: print("\n(dry run — add --apply)")

if __name__ == "__main__":
    main()
